const KST_TZ = 'Asia/Seoul';
const ET_TZ = 'America/New_York';

/** 타임존의 벽시계를 연·월·일·시·분으로 읽는다. hourCycle 을 h23 으로 고정해 자정이 24시로 나오지 않게. */
function wallClock(at: Date, timeZone: string): Record<string, number> {
  const parts = new Intl.DateTimeFormat('en-US', {
    timeZone,
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    hourCycle: 'h23',
  }).formatToParts(at);
  const out: Record<string, number> = {};
  for (const p of parts) {
    if (p.type !== 'literal') {
      out[p.type] = Number(p.value);
    }
  }
  return out;
}

/** 그 순간 해당 타임존이 UTC 로부터 몇 분 앞서는지. 벽시계를 UTC 로 읽어 실제 시각과의 차로 구한다. */
function tzOffsetMinutes(at: Date, timeZone: string): number {
  const w = wallClock(at, timeZone);
  const asUtc = Date.UTC(w.year, w.month - 1, w.day, w.hour, w.minute);
  // at 의 초·밀리초는 오프셋 계산에 영향이 없도록 분 단위로 내림해 비교한다.
  return (asUtc - Math.floor(at.getTime() / 60_000) * 60_000) / 60_000;
}

/**
 * 미 동부 벽시계 시각을 UTC 밀리초로.
 *
 * 서머타임 여부를 'EDT' 같은 표기 문자열로 판정하면 환경에 따라 'GMT-4' 로 나올 때 통째로 틀어지므로,
 * 오프셋을 값으로 구한다. 후보 시각으로 한 번 잡고 그 시점의 오프셋으로 다시 보정하는 2단계 —
 * DST 전환 경계를 사이에 둔 경우까지 맞춘다.
 */
function etToUtcMs(date: string, etTime: string): number {
  const [y, m, d] = date.split('-').map(Number);
  const [hh, mm] = etTime.split(':').map(Number);
  const naive = Date.UTC(y, m - 1, d, hh, mm); // ET 벽시계를 UTC 로 가정한 값
  const guess = naive - tzOffsetMinutes(new Date(naive), ET_TZ) * 60_000;
  return naive - tzOffsetMinutes(new Date(guess), ET_TZ) * 60_000;
}

const pad = (n: number): string => String(n).padStart(2, '0');

/** 발표 시점의 KST 표기 — { date: 'YYYY-MM-DD', time: 'HH:mm' }. 밤 발표는 국내 기준 다음날이 된다. */
export function etToKst(date: string, etTime: string): { date: string; time: string } {
  const w = wallClock(new Date(etToUtcMs(date, etTime)), KST_TZ);
  return {
    date: `${w.year}-${pad(w.month)}-${pad(w.day)}`,
    time: `${pad(w.hour)}:${pad(w.minute)}`,
  };
}
